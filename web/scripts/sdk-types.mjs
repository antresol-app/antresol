// npm run sdk:types: the addon SDK's types (addon-sdk/index.d.ts and
// addon-sdk/types/). tsc declares every module the SDK's program reaches
// (tsconfig.sdk.json, into addon-sdk/.dts); only the declarations that
// src/addons/sdk.ts's own declaration reaches are kept. Generated, not
// committed.
import { execFileSync } from 'node:child_process'
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const web = join(dirname(fileURLToPath(import.meta.url)), '..')
const sdk = join(web, 'addon-sdk')
const tmp = join(sdk, '.dts')
const out = join(sdk, 'types')

rmSync(tmp, { recursive: true, force: true })
execFileSync(join(web, 'node_modules', '.bin', 'tsc'), ['-p', join(web, 'tsconfig.sdk.json')], { stdio: 'inherit' })

// ambient declarations (`declare module '*/vendor/x.js'`) of the sources'
// own .d.ts files: an import that has no emitted declaration takes one of them
const ambient = ['src/vendor/foliate/foliate.d.ts'].map((f) => ({
  file: f,
  patterns: [...readFileSync(join(web, f), 'utf8').matchAll(/declare module '\*(\/[^']+)'/g)].map((m) => m[1]),
}))
const refs = new Set()

const seen = new Set()
const queue = ['addons/sdk.d.ts']
while (queue.length > 0) {
  const f = queue.pop()
  if (seen.has(f)) continue
  seen.add(f)
  const src = readFileSync(join(tmp, f), 'utf8')
  for (const m of src.matchAll(/(?:from\s+|import\(\s*)['"](\.{1,2}\/[^'"]+)['"]/g)) {
    const base = join(dirname(f), m[1])
    const hit = [`${base}.d.ts`, join(base, 'index.d.ts')].find((c) => existsSync(join(tmp, c)))
    if (hit) {
      queue.push(hit)
      continue
    }
    const decl = ambient.find((a) => a.patterns.some((p) => m[1].endsWith(p)))
    if (!decl) throw new Error(`sdk:types: ${f} imports ${m[1]}, which has no declaration`)
    refs.add(decl.file)
  }
}

rmSync(out, { recursive: true, force: true })
for (const f of seen) {
  mkdirSync(dirname(join(out, f)), { recursive: true })
  cpSync(join(tmp, f), join(out, f))
}
const refLines = []
for (const f of refs) {
  const to = f.replace(/^src\//, '')
  mkdirSync(dirname(join(out, to)), { recursive: true })
  cpSync(join(web, f), join(out, to))
  refLines.push(`/// <reference path="./types/${to}" />\n`)
}
rmSync(tmp, { recursive: true, force: true })
writeFileSync(
  join(sdk, 'index.d.ts'),
  `// Generated by \`npm run sdk:types\` (web/scripts/sdk-types.mjs).\n${refLines.join('')}export * from './types/addons/sdk'\n`,
)
console.log(`sdk:types: ${seen.size} declarations in addon-sdk/types`)
